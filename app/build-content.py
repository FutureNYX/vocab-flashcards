"""Merge next/content/batch-*.json and global.json into next/content.js, and check
the whole deck. Run: python next/build-content.py   (from the repo root or anywhere)

Fails loudly on anything that would break a card; prints warnings for things a
human should look at (shared plain phrases, look-alike cues).
"""
import csv, glob, json, os, re, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
KEYS = ["word", "intents", "ru_cue", "plain", "upgrades", "collocations", "ru_trap",
        "nuance", "personal", "gesture", "hook", "forms"]

words = [r["word"] for r in csv.DictReader(open(os.path.join(ROOT, "words.csv"), encoding="utf-8-sig"))]
content = {}
for f in sorted(glob.glob(os.path.join(HERE, "content", "batch-*.json"))):
    for x in json.load(open(f, encoding="utf-8")):
        content[x["word"]] = x
glob_ = json.load(open(os.path.join(HERE, "content", "global.json"), encoding="utf-8"))

errors, warns = [], []
missing = [w for w in words if w not in content]
extra = [w for w in content if w not in words]
if missing: errors.append(f"missing content for: {missing}")
if extra: errors.append(f"content for words not in deck: {extra}")

def stem(w):
    w = w.lower()
    for suf in ("ation", "ness", "ment", "ity", "ing", "ise", "ize", "ed", "es", "ly", "al", "e", "s", "y"):
        if w.endswith(suf) and len(w) - len(suf) >= 4:
            return w[: -len(suf)]
    return w

plain_owner = defaultdict(list)
for w in words:
    c = content.get(w)
    if not c: continue
    for k in KEYS:
        if k not in c: errors.append(f"{w}: no key {k}")
    blob = json.dumps(c, ensure_ascii=False)
    if "ё" in blob or "Ё" in blob: errors.append(f"{w}: contains ё")
    heads = w.split() if " " not in w else [x for x in w.split() if len(x) > 3]
    for i in c.get("intents", []):
        for h in heads:
            if re.search(r"\b" + re.escape(stem(h)), i.lower()):
                errors.append(f"{w}: intent gives the word away: {i!r}")
    if len(c.get("intents", [])) < 3: warns.append(f"{w}: fewer than 3 intents (no held-out probe)")
    for u in c.get("upgrades", []):
        if u["better"].count("*") != 2: errors.append(f"{w}: upgrade 'better' needs one *pair*: {u['better']!r}")
        if not re.search(r"\[[^\]]+\]", u["plain"]): errors.append(f"{w}: upgrade 'plain' needs [brackets]: {u['plain']!r}")
    for k in c.get("collocations", []):
        if "___" not in k.get("frame", ""): errors.append(f"{w}: collocation frame needs ___: {k!r}")
    forms = [x.lower() for x in c.get("forms", [])] + [w.lower()]
    for u in c.get("upgrades", []):
        m = re.search(r"\*([^*]+)\*", u["better"])
        if m and m.group(1).lower() not in forms:
            warns.append(f"{w}: '{m.group(1)}' (in an upgrade) is not in forms, so typing it would be marked wrong")
    for p in c.get("plain", []):
        plain_owner[p.lower().strip()].append(w)
    if w not in glob_.get("word_themes", {}): errors.append(f"{w}: no theme")

for p, owners in plain_owner.items():
    if len(owners) > 1:
        warns.append(f"plain phrase '{p}' is shared by {owners}: the carry-word plan and upgrades may point to either")

fam_words = {x for f in glob_.get("families", []) for x in f["words"]}
for x in fam_words:
    if x not in words: errors.append(f"family word not in deck: {x}")

# what the app loads: content per word, plus the deck-wide data
out = {"words": {w: {k: v for k, v in content[w].items() if k != "word"} for w in words if w in content},
       "global": {"word_themes": glob_["word_themes"], "families": glob_["families"],
                  "themes": {k: v["name"] for k, v in glob_["themes"].items()}, "speak": glob_["speak"]}}
js = ("/* Generated by build-content.py from content/*.json. Edit those, not this. */\n"
      "window.CONTENT = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n")

for e in errors: print("ERROR", e)
for w_ in warns: print("warn ", w_)
if errors:
    sys.exit(1)
open(os.path.join(HERE, "content.js"), "w", encoding="utf-8", newline="\n").write(js)
print(f"ok: {len(out['words'])} words, {len(glob_['families'])} families, {len(glob_['speak'])} speak prompts -> app/content.js")
